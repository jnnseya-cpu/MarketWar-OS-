// npm run lock:update
//
// ACCEPT THE CURRENT SURFACE AS THE LOCKED ONE.
//
// Deliberate on purpose. `check:lock` fails on a removal or a silent change,
// and this is the only way to clear it — which means every accepted change
// arrives as a diff in `docs/DELIVERED.lock.json` that somebody reviews beside
// the change that caused it. A gate that could clear itself would be a gate
// that does nothing.
//
// It prints what it is about to accept before writing, so running it by
// reflex still shows the removal in the terminal.

import { writeFileSync, readFileSync, existsSync } from "node:fs";
import { inventory, flatten, leafCount, LOCK_PATH } from "./lock-inventory.mjs";

const say = (m) => process.stdout.write(m + "\n");

const now = await inventory();

let previous = null;
if (existsSync(LOCK_PATH)) {
  try { previous = JSON.parse(readFileSync(LOCK_PATH, "utf8")); } catch { previous = null; }
}

if (previous?.inventory) {
  const before = flatten(previous.inventory);
  const after = flatten(now);
  const removed = [...before.keys()].filter((k) => !after.has(k));
  const changed = [...before].filter(([k, v]) => after.has(k) && String(after.get(k)) !== String(v));
  const added = [...after.keys()].filter((k) => !before.has(k));

  say("");
  say(`Accepting: +${added.length} added, ${changed.length} changed, ${removed.length} REMOVED.`);
  if (removed.length) {
    say("");
    say("THESE ARE BEING ACCEPTED AS GONE. The additive-only law says a capability");
    say("is only removed on the owner's explicit instruction naming it:");
    for (const r of removed.slice(0, 30)) say(`  - ${r}`);
    if (removed.length > 30) say(`  … and ${removed.length - 30} more`);
  }
  if (changed.length) {
    say("");
    say("AND THESE VALUES ARE BEING ACCEPTED AS CHANGED:");
    for (const [k, v] of changed.slice(0, 30)) say(`  ${k}: ${v}  →  ${after.get(k)}`);
    if (changed.length > 30) say(`  … and ${changed.length - 30} more`);
  }
  say("");
}

const out = {
  // No timestamp. A regenerated-but-identical lock must produce a byte-identical
  // file, or every run of this script is a diff and the diffs stop being read.
  note: "The delivered surface of MarketWar OS, locked. Generated by `npm run lock:update`; enforced by `npm run check:lock`. Anything added passes the gate; anything removed or silently changed fails it. Do not hand-edit — regenerate, and review the diff.",
  lockedItems: leafCount(now),
  inventory: now,
};

writeFileSync(LOCK_PATH, `${JSON.stringify(out, null, 2)}\n`, "utf8");
say(`lock:update — ${out.lockedItems} items locked in docs/DELIVERED.lock.json.`);
say("Commit it beside the change that caused it, so the diff says what moved.");
